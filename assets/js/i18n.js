window.translations = translations;

function setLanguage(lang) {
    if (!translations[lang]) lang = 'fr';
    localStorage.setItem('selectedLang', lang);
    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key] !== undefined) {
            element.innerHTML = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-i18n-attr]').forEach(element => {
        element.getAttribute('data-i18n-attr').split(';').forEach(pair => {
            const [attr, key] = pair.split(':');
            if (attr && key && translations[lang][key] !== undefined) {
                element.setAttribute(attr.trim(), translations[lang][key]);
            }
        });
    });

    document.querySelectorAll('.lang__link').forEach(link => {
        const isActive = link.dataset.lang === lang;
        link.classList.toggle('active', isActive);
        link.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });
}

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('selectedLang') || 'fr';
    setLanguage(savedLang);
});
